import { createHash } from 'node:crypto';
import { readFile, readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { ARTICLES, BASE_PATH } from '../src/lib/site.js';

const buildDir = 'build';
const workerSource = await readFile(new URL('./service-worker.js', import.meta.url), 'utf8');
const files = (await readdir(buildDir, { recursive: true, withFileTypes: true }))
  .filter((entry) => entry.isFile())
  .map((entry) => path.relative(buildDir, path.join(entry.parentPath, entry.name)).split(path.sep).join('/'))
  .filter((file) => !file.startsWith('_app/') && file !== 'sw.js')
  .sort();

const pages = ['', ...ARTICLES.map(({ slug }) => slug + '/'), '404.html'];
const assets = files.filter((file) =>
  file.startsWith('scripts/') || file.startsWith('styles/') || file.startsWith('icons/') ||
  ['i18n.js', 'livedata.js', 'favicon.svg', 'manifest.webmanifest'].includes(file)
);
for (const page of pages) {
  const filename = page.endsWith('.html') ? page : page + 'index.html';
  if (!files.includes(filename)) throw new Error('Missing prerendered page: ' + filename);
}

const hash = createHash('sha256').update(workerSource).update(BASE_PATH);
for (const file of files) {
  const bytes = await readFile(path.join(buildDir, file));
  hash.update(file + '\0').update(createHash('sha256').update(bytes).digest());
}
const version = hash.digest('hex').slice(0, 16);
const precache = [...pages, ...assets].map((file) => BASE_PATH + file);
const config = [
  '// Generated by scripts/build-service-worker.js',
  'const BASE = ' + JSON.stringify(BASE_PATH) + ';',
  'const VERSION = ' + JSON.stringify(version) + ';',
  'const PRECACHE = ' + JSON.stringify(precache, null, 2) + ';',
  ''
].join('\n');

await writeFile(path.join(buildDir, 'sw.js'), config + workerSource);
